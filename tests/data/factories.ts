/** Delete a declaration this suite created (same request as the list's Delete icon). */
export async function deleteDeclaration(page: Page, session: SpnSession, id: string) {
  const res = await page.request.get(
    serviceUrl(session, { SERVICENAME: 'importdeclarationcontrol', ACTION: 'DELETE', SELITEM: `ImDclCtrl:${id}` }),
  )
  if (!res.ok()) throw new Error(`delete ImDclCtrl:${id} → HTTP ${res.status()}`)
}
