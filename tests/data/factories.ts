/**
 * Generate a unique reference string for test data isolation.
 * Each test creates its own data with a unique ref — no shared state, no collisions.
 *
 * Total length is capped at 15 chars, so the suffix gets whatever room the
 * prefix leaves (min 6). The suffix is RANDOM rather than a timestamp slice:
 * a long prefix (e.g. "BOTrenamed") used to truncate away the random part
 * entirely, leaving only a coarse time slice that repeats every ~36 ms — two
 * calls close together could produce the same name (2000 calls → 1 unique).
 */
export function uniqueRef(prefix = 'BOT') {
  const room = Math.max(15 - prefix.length, 6)
  let suffix = ''
  while (suffix.length < room) suffix += Math.random().toString(36).slice(2)
  return `${prefix}${suffix.slice(0, room)}`
}

